"""Where dataset files live.

Two stores share one small interface:

* :class:`LocalFileStore` (default): plain files in a directory, normally a
  Docker volume mounted at ``/data``. Fast to start, nothing else to run.
* :class:`WebHdfsStore` (optional, ``STORAGE_BACKEND=hdfs``): Hadoop HDFS over
  its WebHDFS REST API, for installs that already run an HDFS cluster.

Every dataset row records which store holds its file (``storage_backend``), so
both can be read side by side while existing HDFS data is migrated.
"""
from __future__ import annotations

import asyncio
import os
import re
import secrets
import shutil
from pathlib import Path
from typing import AsyncIterator, BinaryIO, Protocol

import httpx
import structlog

from shared.common.exceptions import StorageError

logger = structlog.get_logger(__name__)

CHUNK = 1024 * 1024

LOCAL = "local"
HDFS = "hdfs"
BACKENDS = (LOCAL, HDFS)


class FileTooLarge(StorageError):
    """The upload is bigger than the configured limit."""

    http_status = 413
    error_code = "FILE_TOO_LARGE"


class StorageFull(StorageError):
    """Storing the upload would leave less free disk space than configured."""

    http_status = 507
    error_code = "INSUFFICIENT_STORAGE"


class StoreUnavailable(StorageError):
    """The dataset is in a store that is not running (HDFS turned off)."""

    http_status = 503
    error_code = "STORAGE_UNAVAILABLE"


class BlobStore(Protocol):
    name: str

    async def put(self, key: str, src: BinaryIO, max_bytes: int) -> int:
        """Store ``src`` under ``key``; return its size. Never leaves a partial file."""

    def open(self, key: str) -> AsyncIterator[bytes]:
        """Stream the file's bytes."""

    async def delete(self, key: str) -> None:
        """Remove the file; a missing file is not an error."""

    async def ready(self) -> bool:
        """True when the store can be used."""


# --- local files -------------------------------------------------------------

# Keys are generated by the service ("raw/<uuid>.<ext>"); anything else is
# refused, so a key can never point outside the data directory.
_LOCAL_KEY = re.compile(r"^raw/[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}\.(csv|parquet)$")


class LocalFileStore:
    name = LOCAL

    def __init__(self, root: str | os.PathLike[str], min_free_bytes: int = 0) -> None:
        self.root = Path(root).resolve()
        self.min_free_bytes = min_free_bytes

    def _path(self, key: str) -> Path:
        if not _LOCAL_KEY.fullmatch(key):
            raise StorageError("Invalid storage key")
        path = (self.root / key).resolve()
        if self.root not in path.parents:
            raise StorageError("Invalid storage key")
        return path

    def prepare(self) -> None:
        """Create the directory layout and check it is writable (at startup)."""
        (self.root / "raw").mkdir(parents=True, exist_ok=True)
        probe = self.root / f".write-test-{secrets.token_hex(4)}"
        probe.write_bytes(b"")
        probe.unlink()

    def free_bytes(self) -> int:
        return shutil.disk_usage(self.root).free

    async def put(self, key: str, src: BinaryIO, max_bytes: int) -> int:
        target = self._path(key)
        return await asyncio.to_thread(self._put_sync, target, src, max_bytes)

    def _put_sync(self, target: Path, src: BinaryIO, max_bytes: int) -> int:
        if self.min_free_bytes and self.free_bytes() < self.min_free_bytes:
            raise StorageFull("Not enough free disk space to store the dataset")
        target.parent.mkdir(parents=True, exist_ok=True)
        tmp = target.with_name(f".{target.name}.{secrets.token_hex(6)}.tmp")
        size = 0
        try:
            with open(tmp, "xb") as out:
                while True:
                    chunk = src.read(CHUNK)
                    if not chunk:
                        break
                    size += len(chunk)
                    if size > max_bytes:
                        raise FileTooLarge(f"The file is larger than the {max_bytes} byte limit")
                    out.write(chunk)
                out.flush()
                os.fsync(out.fileno())
            os.replace(tmp, target)
        except BaseException:
            tmp.unlink(missing_ok=True)
            raise
        logger.info("dataset_file_stored", backend=LOCAL, key=target.relative_to(self.root).as_posix(), size=size)
        return size

    async def open(self, key: str) -> AsyncIterator[bytes]:
        path = self._path(key)
        try:
            fh = await asyncio.to_thread(open, path, "rb")
        except FileNotFoundError as exc:
            raise StorageError("The dataset file is missing") from exc
        try:
            while True:
                chunk = await asyncio.to_thread(fh.read, CHUNK)
                if not chunk:
                    break
                yield chunk
        finally:
            fh.close()

    async def delete(self, key: str) -> None:
        path = self._path(key)
        await asyncio.to_thread(path.unlink, missing_ok=True)

    async def ready(self) -> bool:
        return self.root.is_dir() and os.access(self.root, os.W_OK)


# --- HDFS (optional) ---------------------------------------------------------

_HDFS_KEY = re.compile(r"^/[A-Za-z0-9_./-]+$")


class WebHdfsStore:
    """HDFS through WebHDFS: the namenode redirects each request to a datanode."""

    name = HDFS

    def __init__(self, webhdfs_url: str, user: str = "hadoop", transport: httpx.AsyncBaseTransport | None = None) -> None:
        self.base = webhdfs_url.rstrip("/")
        self.user = user
        self._transport = transport  # tests only
        # Generous: a cold first write (namenode redirect + datanode pipeline)
        # can take several seconds.
        self.timeout = httpx.Timeout(300.0, connect=10.0)

    def _url(self, key: str, op: str, extra: str = "") -> str:
        if not _HDFS_KEY.fullmatch(key) or ".." in key:
            raise StorageError("Invalid storage key")
        return f"{self.base}/webhdfs/v1{key}?op={op}&user.name={self.user}{extra}"

    async def put(self, key: str, src: BinaryIO, max_bytes: int) -> int:
        url = self._url(key, "CREATE", "&overwrite=true")
        size = 0

        async def body() -> AsyncIterator[bytes]:
            nonlocal size
            while True:
                chunk = await asyncio.to_thread(src.read, CHUNK)
                if not chunk:
                    break
                size += len(chunk)
                if size > max_bytes:
                    raise FileTooLarge(f"The file is larger than the {max_bytes} byte limit")
                yield chunk

        async with httpx.AsyncClient(timeout=self.timeout, transport=self._transport) as client:
            try:
                first = await client.put(url, follow_redirects=False)
                if first.status_code != 307 or "location" not in first.headers:
                    raise StorageError(f"Unexpected WebHDFS response {first.status_code}")
                response = await client.put(first.headers["location"], content=body())
                response.raise_for_status()
            except FileTooLarge:
                await self.delete(key)
                raise
            except httpx.HTTPError as exc:
                logger.error("hdfs_upload_error", error=str(exc), key=key)
                raise StorageError(f"Failed to store the file in HDFS: {exc}") from exc
        logger.info("dataset_file_stored", backend=HDFS, key=key, size=size)
        return size

    async def open(self, key: str) -> AsyncIterator[bytes]:
        url = self._url(key, "OPEN")
        async with httpx.AsyncClient(timeout=self.timeout, follow_redirects=True, transport=self._transport) as client:
            try:
                async with client.stream("GET", url) as response:
                    if response.status_code == 404:
                        raise StorageError("The dataset file is missing")
                    response.raise_for_status()
                    async for chunk in response.aiter_bytes(CHUNK):
                        yield chunk
            except httpx.HTTPError as exc:
                logger.error("hdfs_download_error", error=str(exc), key=key)
                raise StorageError(f"Failed to read the file from HDFS: {exc}") from exc

    async def delete(self, key: str) -> None:
        url = self._url(key, "DELETE", "&recursive=false")
        async with httpx.AsyncClient(timeout=self.timeout, follow_redirects=True, transport=self._transport) as client:
            try:
                (await client.delete(url)).raise_for_status()
            except httpx.HTTPError as exc:
                raise StorageError(f"Failed to delete the file from HDFS: {exc}") from exc

    async def ready(self) -> bool:
        try:
            async with httpx.AsyncClient(timeout=3.0, transport=self._transport) as client:
                r = await client.get(f"{self.base}/webhdfs/v1/?op=GETFILESTATUS&user.name={self.user}")
                return r.status_code == 200
        except httpx.HTTPError:
            return False


def local_key(dataset_id: str, file_format: str) -> str:
    return f"raw/{dataset_id}.{file_format}"


def hdfs_key(dataset_id: str, file_format: str, base_path: str = "/platform") -> str:
    return f"{base_path.rstrip('/')}/raw/{dataset_id}.{file_format}"


def build_stores(settings) -> dict[str, BlobStore]:
    """Every store, keyed by backend name. HDFS is only contacted when used."""
    return {
        LOCAL: LocalFileStore(settings.data_dir, settings.min_free_disk_bytes),
        HDFS: WebHdfsStore(settings.hdfs_webhdfs_url, settings.hdfs_user),
    }


def new_key(backend: str, dataset_id: str, file_format: str, settings) -> str:
    """The key a new dataset file gets in ``backend``."""
    if backend == HDFS:
        return hdfs_key(dataset_id, file_format, settings.hdfs_base_path)
    return local_key(dataset_id, file_format)
